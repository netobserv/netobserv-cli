// Command gendocs regenerates docs/netobserv_cli.adoc from the client plugin's own Cobra command
// tree, replacing scripts/generate-doc.sh (which reformatted scripts/help.sh's hand-maintained
// usage text via a chain of sed substitutions). Generating straight from the live flag
// definitions means the docs can't drift from actual CLI behavior the way a hand-duplicated text
// block could. Invoked via `make docs`; not shipped to users.
package main

import (
	"fmt"
	"log"
	"os"
	"sort"
	"strings"

	"github.com/spf13/cobra"
	"github.com/spf13/pflag"

	commands "github.com/netobserv/network-observability-cli/internal/plugin/commands"
)

const outputPath = "./docs/netobserv_cli.adoc"

func main() {
	if err := run(); err != nil {
		log.Fatal(err)
	}
}

func run() error {
	root := commands.NewRootCommand("oc-netobserv", "main")

	var b strings.Builder
	writeHeader(&b, root)
	writeBasicCommands(&b, root)
	for _, name := range []string{"flows", "packets", "metrics"} {
		cmd, _, err := root.Find([]string{name})
		if err != nil {
			return fmt.Errorf("command %q not found: %w", name, err)
		}
		writeCommandSection(&b, cmd)
	}

	content := strings.TrimRight(b.String(), "\n") + "\n"
	return os.WriteFile(outputPath, []byte(content), 0o644)
}

func writeHeader(b *strings.Builder, root *cobra.Command) {
	fmt.Fprintf(b, "// Automatically generated by 'go run ./cmd/devtools/gendocs'. Do not edit, or make the NETOBSERV team aware of the edits.\n")
	fmt.Fprintf(b, ":_mod-docs-content-type: REFERENCE\n\n")
	fmt.Fprintf(b, "[id=\"network-observability-netobserv-cli-reference_{context}\"]\n")
	fmt.Fprintf(b, "= Network Observability CLI usage\n\n")
	fmt.Fprintf(b, "You can use the Network Observability CLI (`oc netobserv`) to pass command line arguments to capture flows data, packets data, and metrics for further analysis and enable features supported by the Network Observability Operator.\n\n")
	fmt.Fprintf(b, "[id=\"cli-syntax_{context}\"]\n== Syntax\n%s\n\n", root.Long)
	if root.Example != "" {
		fmt.Fprintf(b, ".Examples\n[source,terminal]\n----\n%s\n----\n\n", root.Example)
	}
}

func writeBasicCommands(b *strings.Builder, root *cobra.Command) {
	fmt.Fprintf(b, "[id=\"cli-basic-commands_{context}\"]\n== Basic commands\n")
	fmt.Fprintf(b, "[cols=\"3a,8a\",options=\"header\"]\n.Basic commands\n|===\n| Command | Description\n")
	for _, cmd := range root.Commands() {
		if cmd.Hidden || cmd.Name() == "help" || cmd.Name() == "completion" {
			continue
		}
		fmt.Fprintf(b, "| %s\n| %s\n", cmd.Name(), cmd.Short)
	}
	fmt.Fprintf(b, "|===\n\n")

	fmt.Fprintf(b, "[id=\"cli-global-options_{context}\"]\n== Global options\n")
	fmt.Fprintf(b, "These options apply to every command.\n\n")
	fmt.Fprintf(b, "[cols=\"1,1,1\",options=\"header\"]\n|===\n| Option | Description | Default\n")
	var flags []*pflag.Flag
	root.PersistentFlags().VisitAll(func(f *pflag.Flag) { flags = append(flags, f) })
	sort.Slice(flags, func(i, j int) bool { return flags[i].Name < flags[j].Name })
	for _, f := range flags {
		def := f.DefValue
		if def == "" || def == "[]" {
			def = "-"
		}
		fmt.Fprintf(b, "| --%s\n| %s\n| %s\n", f.Name, f.Usage, def)
	}
	fmt.Fprintf(b, "|===\n\n")
}

func writeCommandSection(b *strings.Builder, cmd *cobra.Command) {
	fmt.Fprintf(b, "[id=\"cli-reference-%s-capture-options_{context}\"]\n== %s capture options\n", cmd.Name(), strings.ToUpper(cmd.Name()[:1])+cmd.Name()[1:])
	fmt.Fprintf(b, "%s\n\n", cmd.Long)
	fmt.Fprintf(b, ".`oc netobserv %s` syntax\n[source,terminal]\n----\n$ oc netobserv %s [<option>]\n----\n\n", cmd.Name(), cmd.Name())

	fmt.Fprintf(b, "[cols=\"1,1,1\",options=\"header\"]\n|===\n| Option | Description | Default\n")
	var flags []*pflag.Flag
	cmd.Flags().VisitAll(func(f *pflag.Flag) { flags = append(flags, f) })
	sort.Slice(flags, func(i, j int) bool { return flags[i].Name < flags[j].Name })
	for _, f := range flags {
		def := f.DefValue
		if def == "" || def == "[]" {
			def = "-"
		}
		fmt.Fprintf(b, "| --%s\n| %s\n| %s\n", f.Name, f.Usage, def)
	}
	fmt.Fprintf(b, "|===\n\n")

	if cmd.Example != "" {
		fmt.Fprintf(b, ".Example\n[source,terminal]\n----\n%s\n----\n\n", cmd.Example)
	}
}
